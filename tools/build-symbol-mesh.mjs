// Builds the data for the solid 3D symbol on the holding page.
// It reads the official symbol outline (brand/symbol-white.svg), samples it into an even, smooth contour,
// triangulates the flat front face, and writes both into the marked block in index.html.
// The page builds the real solid (front, back, rounded edge, side walls) from this contour in WebGL.
// Run:  npm i --no-save earcut  &&  node tools/build-symbol-mesh.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const _e = require('earcut'); const earcut = _e.default || _e.earcut || _e;
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const N = 1000, Q = 30000, BEVEL = 0.012; // keep BEVEL equal to the page's value

const svg = readFileSync(join(ROOT, 'brand/symbol-white.svg'), 'utf8');
const d = svg.match(/ d="([^"]+)"/)[1];
const t = d.match(/[MCZ]|-?\d+\.?\d*/g);
let i = 0, pts = [], cur = null;
while (i < t.length) {
  const c = t[i++];
  if (c === 'M') { cur = [+t[i++], +t[i++]]; pts.push(cur); }
  else if (c === 'C') {
    while (i < t.length && !/[A-Z]/.test(t[i])) {
      const a = [+t[i++], +t[i++]], b = [+t[i++], +t[i++]], e = [+t[i++], +t[i++]];
      for (let k = 1; k <= 48; k++) {
        const u = k / 48, v = 1 - u;
        pts.push([v*v*v*cur[0] + 3*v*v*u*a[0] + 3*v*u*u*b[0] + u*u*u*e[0], v*v*v*cur[1] + 3*v*v*u*a[1] + 3*v*u*u*b[1] + u*u*u*e[1]]);
      }
      cur = e;
    }
  }
}
// centre, scale to width 1, flip y (SVG is y-down)
let x0 = 1e9, x1 = -1e9, y0 = 1e9, y1 = -1e9;
for (const p of pts) { x0 = Math.min(x0, p[0]); x1 = Math.max(x1, p[0]); y0 = Math.min(y0, p[1]); y1 = Math.max(y1, p[1]); }
const S = x1 - x0, cx = (x0 + x1) / 2, cy = (y0 + y1) / 2;
pts = pts.map(p => [(p[0] - cx) / S, -(p[1] - cy) / S]);
// even arc-length resample
const L = [0]; for (let k = 1; k < pts.length; k++) L.push(L[k-1] + Math.hypot(pts[k][0]-pts[k-1][0], pts[k][1]-pts[k-1][1]));
L.push(L[L.length-1] + Math.hypot(pts[0][0]-pts[pts.length-1][0], pts[0][1]-pts[pts.length-1][1])); pts.push(pts[0]);
const tot = L[L.length-1]; let out = [], j = 0;
for (let k = 0; k < N; k++) { const s = tot * k / N; while (L[j+1] < s) j++; const f = (s - L[j]) / (L[j+1] - L[j] || 1);
  out.push([pts[j][0] + (pts[j+1][0]-pts[j][0])*f, pts[j][1] + (pts[j+1][1]-pts[j][1])*f]); }
// quantise (what the page will read)
let q = out.map(p => [Math.round(p[0]*Q), Math.round(p[1]*Q)]);
let area = 0; for (let k = 0; k < N; k++) { const a = q[k], b = q[(k+1)%N]; area += a[0]*b[1] - b[0]*a[1]; }
if (area < 0) q.reverse();                       // counter-clockwise
const P = q.map(p => [p[0]/Q, p[1]/Q]);
// same inset as the page: move every point inward along its smoothed outward normal
function normals(P) { return P.map((p, k) => { const a = P[(k-3+N)%N], b = P[(k+3)%N]; const tx = b[0]-a[0], ty = b[1]-a[1], l = Math.hypot(tx, ty) || 1; return [ty/l, -tx/l]; }); }
const nm = normals(P);
const inset = P.map((p, k) => [p[0] - nm[k][0]*BEVEL, p[1] - nm[k][1]*BEVEL]);
const idx = earcut(inset.flat());
// check the triangulation covers the face
let ta = 0; for (let k = 0; k < idx.length; k += 3) { const a = inset[idx[k]], b = inset[idx[k+1]], c = inset[idx[k+2]]; ta += Math.abs((b[0]-a[0])*(c[1]-a[1]) - (c[0]-a[0])*(b[1]-a[1])) / 2; }
let pa = 0; for (let k = 0; k < N; k++) { const a = inset[k], b = inset[(k+1)%N]; pa += a[0]*b[1] - b[0]*a[1]; } pa = Math.abs(pa) / 2;
if (Math.abs(ta - pa) / pa > 1e-3) throw new Error('triangulation does not cover the face: ' + ta + ' vs ' + pa);
const b64 = (arr, T) => Buffer.from(new T(arr).buffer).toString('base64');
const block = `/*Q-MESH-BEGIN (generated by tools/build-symbol-mesh.mjs; do not edit by hand)*/\nvar QM={n:${N},q:${Q},h:${(y1-y0)/S},c:"${b64(q.flat(), Int16Array)}",i:"${b64(idx, Uint16Array)}"};\n/*Q-MESH-END*/`;
const file = join(ROOT, 'index.html');
let html = readFileSync(file, 'utf8');
const re = /\/\*Q-MESH-BEGIN[\s\S]*?Q-MESH-END\*\//;
if (!re.test(html)) { console.log(block); process.exit(0); }
writeFileSync(file, html.replace(re, () => block));
console.log('contour points', N, 'face triangles', idx.length / 3, 'height/width', ((y1-y0)/S).toFixed(4), 'face area ok', pa.toFixed(4));
